/**
 * Copies the deployment manifest and the WhiskyDistillery ABI from `smart_contracts/deployments/`
 * into `src/generated/`. This is a build-time copy: no runtime code imports `smart_contracts/`.
 *
 *   pnpm --filter @idpp/passport-config sync-contracts             # copy manifest + ABI
 *   pnpm --filter @idpp/passport-config sync-contracts --abi-only  # regenerate abi.ts from abi.json
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const generatedDir = resolve(here, "../src/generated");
const deploymentsDir = resolve(here, "../../../../smart_contracts/deployments");

type ManifestChain = {
  network: string;
  chainId: number;
  eid: number;
  address: string;
  deploymentBlock: number;
};
type Manifest = { deploymentId: string; chains: ManifestChain[] };

function fail(message: string): never {
  console.error(`sync-contracts: ${message}`);
  process.exit(1);
}

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

function writeJson(path: string, value: unknown): void {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
}

/** Writes `abi.ts`, a literal `as const` copy of `abi.json` so viem can infer types. */
function writeAbiModule(abi: unknown): void {
  const body = JSON.stringify(abi, null, 2);
  writeFileSync(
    resolve(generatedDir, "abi.ts"),
    `// Generated by scripts/sync-contracts.ts from abi.json. Do not edit.\nexport const whiskyDistilleryAbi = ${body} as const;\n`,
  );
}

function validateManifest(manifest: Manifest): void {
  if (typeof manifest.deploymentId !== "string" || manifest.deploymentId.length === 0) {
    fail("manifest.deploymentId is missing");
  }
  if (!Array.isArray(manifest.chains) || manifest.chains.length === 0) {
    fail("manifest.chains is empty");
  }
  for (const chain of manifest.chains) {
    for (const key of ["network", "chainId", "eid", "address", "deploymentBlock"] as const) {
      if (chain[key] === undefined) fail(`manifest chain ${JSON.stringify(chain)} lacks ${key}`);
    }
    if (!/^0x[0-9a-fA-F]{40}$/.test(chain.address)) fail(`bad address ${chain.address}`);
  }
}

function main(): void {
  mkdirSync(generatedDir, { recursive: true });

  if (process.argv.includes("--abi-only")) {
    writeAbiModule(readJson(resolve(generatedDir, "abi.json")));
    console.log("sync-contracts: regenerated abi.ts from abi.json");
    return;
  }

  const manifestPath = resolve(deploymentsDir, "manifest.json");
  if (!existsSync(manifestPath)) fail(`manifest not found at ${manifestPath}`);
  const manifest = readJson<Manifest>(manifestPath);
  validateManifest(manifest);

  const first = manifest.chains[0] as ManifestChain;
  const deploymentPath = resolve(deploymentsDir, first.network, "WhiskyDistillery.json");
  if (!existsSync(deploymentPath)) fail(`deployment record not found at ${deploymentPath}`);
  const { abi } = readJson<{ abi: unknown }>(deploymentPath);
  if (!Array.isArray(abi)) fail(`${deploymentPath} has no abi array`);

  writeJson(resolve(generatedDir, "manifest.json"), manifest);
  writeJson(resolve(generatedDir, "abi.json"), abi);
  writeAbiModule(abi);
  console.log(
    `sync-contracts: wrote manifest (${manifest.deploymentId}, ${manifest.chains.length} chains) and ABI (${abi.length} entries)`,
  );
}

main();
